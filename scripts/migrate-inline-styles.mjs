// Convert inline style="…" attributes in the research archive (Gojo and
// Lelouch posts) into generated classes, and wrap tables for horizontal
// scrolling on narrow screens.
//
//   node scripts/migrate-inline-styles.mjs           # dry run: counts
//   node scripts/migrate-inline-styles.mjs --apply   # rewrite pages + CSS
//
// Every distinct declaration string becomes one class (.ia-N) whose
// declarations carry !important, which reproduces the cascade position an
// inline style had (beats normal author rules, loses to later !important
// rules). Dark-mode overrides that used to match on [style*="#hex"] are
// regenerated to target the classes that carry those colours, so
// authored-dark.css keeps working without attribute-substring selectors.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { walkPages } from './lib/pages.mjs';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
export const CSS_PATH = 'resources/css/components/authored-inline.css';
export const DARK_PATH = 'resources/css/components/authored-dark.css';
const SCOPE = /^\/research\//;

// Dark-mode retints, mirroring the original authored-dark.css intent.
export const DARK_BACKGROUNDS = [
  [['#dcfce7', '#f0fdf4', '#bbf7d0', '#86efac'], 'rgba(34, 197, 94, 0.13)'],
  [['#fef9c3', '#fefce8', '#fffbeb', '#fef3c7', '#fff7ed', '#fef9ee'], 'rgba(245, 158, 11, 0.13)'],
  [['#fee2e2', '#fef2f2', '#fff0f0'], 'rgba(239, 68, 68, 0.13)'],
  [['#f3f4f6', '#f8fafc', '#f8f9fa', '#f8f8f8', '#f4f4f4', '#f9f9f9', '#fafafa', '#e2e8f0', '#e5e5e5', '#e5e7eb'], 'rgba(255, 255, 255, 0.06)'],
  [['#f5f3ff'], 'rgba(124, 58, 237, 0.16)'],
];
export const DARK_TEXT = [
  [['#166534', '#15803d', '#16a34a'], '#4ade80'],
  [['#713f12', '#854d0e', '#92400e', '#d97706'], '#fcd34d'],
  [['#991b1b', '#b00'], '#fca5a5'],
  [['#374151'], '#d4d4d4'],
];

export function normalise(style) {
  return style.trim().replace(/\s+/g, ' ').replace(/;\s*$/, '');
}

// Rewrite one document. Returns { html, styles: Map<normalisedStyle, count> }.
export function convertDocument(html, classFor) {
  const styles = new Map();
  let out = html.replace(/<([a-zA-Z][\w-]*)((?:\s+[^\s=>]+(?:="[^"]*")?)*)\s*(\/?)>/g, (m, tag, attrs, selfClose) => {
    const sm = attrs.match(/\sstyle="([^"]*)"/);
    if (!sm) return m;
    const style = normalise(sm[1]);
    if (!style) return `<${tag}${attrs.replace(sm[0], '')}${selfClose}>`;
    styles.set(style, (styles.get(style) || 0) + 1);
    const cls = classFor(style);
    let rest = attrs.replace(sm[0], '');
    const cm = rest.match(/\sclass="([^"]*)"/);
    if (cm) rest = rest.replace(cm[0], ` class="${cm[1].split(/\s+/).filter(Boolean).concat(cls).join(' ')}"`);
    else rest = ` class="${cls}"` + rest;
    return `<${tag}${rest}${selfClose}>`;
  });
  // Wrap bare tables so wide ones scroll inside their own container.
  out = out.replace(/(<div class="tablewrap">\s*)?<table\b([\s\S]*?)<\/table>/g, (m, wrapped, inner) => wrapped ? m : `<div class="tablewrap"><table${inner}</table></div>`);
  return { html: out, styles };
}

// Extract the property a hex colour is used for in a declaration string.
function propsWithHex(style, hex) {
  return style.split(';').map(d => d.trim()).filter(d => d.toLowerCase().includes(hex)).map(d => d.split(':')[0].trim().toLowerCase());
}

export function generateCss(classes) {
  const lines = ['/* Generated by scripts/migrate-inline-styles.mjs from the inline styles',
    '   that Gojo and Lelouch posts used to carry. Declarations are !important so',
    '   each class keeps the cascade position of the inline style it replaced.',
    '   Do not edit by hand: re-run the script. */', ''];
  for (const [style, cls] of classes) lines.push(`.${cls} { ${style.split(';').map(d => d.trim()).filter(Boolean).map(d => d + ' !important').join('; ')}; }`);
  return lines.join('\n') + '\n';
}

export function generateDarkCss(classes) {
  const bg = [], text = [];
  for (const [style, cls] of classes) {
    const lower = style.toLowerCase();
    for (const [hexes, dark] of DARK_BACKGROUNDS) for (const h of hexes) {
      if (lower.includes(h) && propsWithHex(lower, h).some(p => /^background/.test(p))) bg.push([cls, dark]);
    }
    for (const [hexes, dark] of DARK_TEXT) for (const h of hexes) {
      if (lower.includes(h) && propsWithHex(lower, h).some(p => p === 'color')) text.push([cls, dark]);
    }
  }
  const group = pairs => { const m = new Map(); for (const [c, v] of pairs) { if (!m.has(v)) m.set(v, new Set()); m.get(v).add(c); } return m; };
  const lines = ['/* ============================================',
    '   AUTHORED-CONTENT DARK-MODE OVERRIDES',
    '   Generated by scripts/migrate-inline-styles.mjs. Gojo and Lelouch posts',
    '   carried hard-coded light colours in inline styles; those are now the',
    '   .ia-N classes in authored-inline.css, and these rules retint them for',
    '   dark mode only. Imported after authored-inline.css so they win ties.',
    '   ============================================ */', ''];
  lines.push('/* Light pastel backgrounds and borders → dark tints of the same hue */');
  for (const [v, cls] of group(bg)) lines.push(`${[...cls].map(c => `[data-theme="dark"] .${c}`).join(',\n')} { background-color: ${v} !important; }`);
  lines.push('', '/* Dark text colours → light equivalents readable on the dark tints */');
  for (const [v, cls] of group(text)) lines.push(`${[...cls].map(c => `[data-theme="dark"] .${c}`).join(',\n')} { color: ${v} !important; }`);
  return lines.join('\n') + '\n';
}

export function run({ apply }) {
  const pages = walkPages(ROOT).filter(p => SCOPE.test(p.url));
  // First pass: collect distinct styles in a stable order.
  const all = new Map();
  for (const { file } of pages) {
    const { styles } = convertDocument(readFileSync(file, 'utf8'), () => 'x');
    for (const [s, n] of styles) all.set(s, (all.get(s) || 0) + n);
  }
  const classes = new Map([...all.keys()].sort().map((s, i) => [s, `ia-${i + 1}`]));
  let changed = 0, attrs = 0;
  for (const { file } of pages) {
    const src = readFileSync(file, 'utf8');
    const { html, styles } = convertDocument(src, s => classes.get(s));
    for (const n of styles.values()) attrs += n;
    if (html !== src) { changed++; if (apply) writeFileSync(file, html); }
  }
  if (apply && classes.size) {
    writeFileSync(join(ROOT, CSS_PATH), generateCss(classes));
    writeFileSync(join(ROOT, DARK_PATH), generateDarkCss(classes));
  }
  console.log(`${apply ? 'APPLIED' : 'DRY-RUN'}: ${attrs} inline styles across ${changed} pages → ${classes.size} classes`);
  return { changed, attrs, classes };
}

if (process.argv[1] && process.argv[1].endsWith('migrate-inline-styles.mjs')) run({ apply: process.argv.includes('--apply') });
